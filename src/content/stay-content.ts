/**
 * Repo-managed stay content, keyed by OwnerRez property id.
 *
 * WHY THIS FILE EXISTS (permanent, not a stopgap): the OwnerRez account does not
 * carry the "WordPress Plugin + Integrated Websites" add-on, so /v2/listings —
 * the endpoint that would serve descriptions, galleries and amenity lists — is
 * unavailable. OwnerRez therefore owns OPERATIONAL data (address, geo, bed/bath,
 * sleeps, living area, display order, active/snoozed, cover thumbnail) and this
 * file owns EDITORIAL data. The two are merged by id in
 * services/stay-mapper.ts; the id is immutable, display names are not.
 *
 * When /api/properties is unreachable this file renders on its own as the
 * offline catalog, which is what the `offline` block exists for.
 *
 * To onboard a stay: add an entry keyed by its OwnerRez property id.
 * Photography is served from the OwnerRez CDN (uc.orez.io).
 */

export interface StayContentOfflineFacts {
  locality: string;
  region: string;
  bedrooms: number;
  bathrooms: number;
  sleeps: number;
  kind: string;
}

